export type AccessAction = {
  title: string;
  message: string;
  confirmLabel: string;
};

// Centralize consequences for access-sensitive CRUD surfaces; keep this mapping
// aligned with API routes. Never interpolate credentials or factor secrets.
export function accessAction(
  path: string,
  method: string,
  body?: unknown,
): AccessAction | null {
  const route = path.split("?")[0];
  const data = (body || {}) as Record<string, unknown>;
  const action = (
    title: string,
    message: string,
    confirmLabel = "Подтвердить изменение",
  ) => ({ title, message, confirmLabel });
  if (method === "GET") return null;
  if (method === "DELETE" && /^\/announcements\/[^/]+$/.test(route))
    return action(
      "Удалить сообщение?",
      "Сообщение будет удалено из обзора и списка сообщений. Восстановить его через интерфейс нельзя. Событие удаления сохранится в аудите.",
      "Удалить сообщение",
    );
  if (route === "/me/totp/rotate/begin")
    return action(
      "Начать замену TOTP?",
      "Старый фактор продолжит работать, пока вы не подтвердите новый код. Отмена не меняет доступ.",
      "Начать замену",
    );
  if (route === "/me/totp/rotate/finish")
    return action(
      "Заменить TOTP?",
      "Старый TOTP и прежние резервные коды перестанут работать. Сохраните новый секрет в приложении аутентификации. Другие сессии будут завершены.",
      "Заменить TOTP",
    );
  if (route === "/me/passkey/begin")
    return action(
      "Добавить passkey?",
      "Passkey станет фактором входа. Вход только по паролю будет дополнительно защищён MFA. Прежние сессии и коды восстановления будут заменены.",
      "Добавить passkey",
    );
  if (route === "/me/totp/finish")
    return action(
      "Включить TOTP?",
      "Для входа по паролю потребуется код TOTP. Убедитесь, что запись сохранена в приложении аутентификации. Прежние сессии и коды восстановления будут заменены.",
      "Включить TOTP",
    );
  if (route === "/me/factor-policy")
    return action(
      "Изменить требования к входу?",
      "Требования администратора сохраняются. Если выбранные факторы ещё не зарегистрированы, останется доступ только к их регистрации; доступ к нодам будет отозван до завершения настройки.",
    );
  if (/^\/users\/[^/]+\/status$/.test(route) && data.status !== "active")
    return action(
      data.status === "deleted"
        ? "Удалить пользователя?"
        : "Заблокировать пользователя?",
      "Сессии будут завершены. Учётная запись на нодах будет заблокирована, ключи, пароль и sudo-права отозваны. Применение требует связи с каждой нодой.",
      data.status === "deleted" ? "Удалить и отозвать доступ" : "Заблокировать",
    );
  if (/^\/users\/[^/]+\/status$/.test(route) && data.status === "active")
    return action(
      "Разблокировать пользователя?",
      "Сохранённые назначения и действующие SSH-ключи снова будут применены на нодах, если выполнены требования факторов и меток доступа.",
      "Разблокировать",
    );
  if (
    method === "DELETE" &&
    /^\/users\/[^/]+\/(totp|passkeys\/[^/]+)$/.test(route)
  )
    return action(
      "Отвязать фактор входа?",
      "Фактор перестанет работать, прежние сессии будут завершены. Обязательные требования останутся: при нехватке факторов пользователь сможет только завершить их регистрацию.",
      "Отвязать фактор",
    );
  if (method === "PUT" && /^\/users\/[^/]+(\/mfa-policy)?$/.test(route))
    return action(
      "Сохранить параметры пользователя?",
      "Политика входа, синхронизация UNIX-учётки и UNIX-профиль влияют на доступ. Выключение синхронизации отзовёт ключи, пароль и sudo на ранее назначенных нодах. Изменение обязательных факторов может ограничить вход до их регистрации, а shell и POSIX-параметров — работу на нодах. Прежние сессии будут завершены.",
    );
  if (method === "PUT" && route.endsWith("/linux-password"))
    return action(
      "Изменить UNIX-пароль?",
      "Прежний пароль на назначенных нодах перестанет работать после синхронизации. Пустое значение отключает вход по UNIX-паролю.",
    );
  if (method === "DELETE" && route.startsWith("/keys/"))
    return action(
      "Отозвать SSH-ключ?",
      "Ключ будет удалён с назначенных нод после синхронизации. Повторно добавить отозванный ключ нельзя.",
      "Отозвать ключ",
    );
  if (/^\/(bindings|unix-assignments)(\/[^/]+)?$/.test(route))
    return action(
      "Изменить назначение доступа?",
      "Изменятся роли, доступ к нодам и sudo-права затронутых пользователей. Удаление последнего назначения отзовёт доступ.",
    );
  if (route === "/security/labels")
    return action(
      "Изменить метки доступа?",
      "Мандатные ограничения применятся ко всем затронутым пользователям и группам нод. Несовместимые уровни или метки отзовут доступ.",
    );
  if (method === "PUT" && route === "/settings")
    return action(
      "Изменить настройки доступа?",
      "Обязательные SK-ключи могут отозвать обычные SSH-ключи. Изменение срока сертификатов запускает перевыпуск на всех нодах; offline-ноды обновятся после подключения. Сроки жизни ключей, параметры синхронизации и доступ к API/MCP будут применены по сохранённой конфигурации.",
    );
  if (
    route === "/nodes/move" ||
    (method === "PUT" && /^\/nodes\/[^/]+(\/ssh)?$/.test(route))
  )
    return action(
      "Изменить параметры нод?",
      "Перенос между группами меняет назначения доступа и sudo. Отключение ноды прекращает управление доступом; изменение SSH-адреса влияет на команды подключения и inventory.",
    );
  if (
    method === "DELETE" &&
    /^\/(roles|groups|user-groups|unix-groups)\/[^/]+$/.test(route)
  )
    return action(
      "Удалить объект доступа?",
      "Связанные назначения и требования будут пересчитаны. Пользователи могут потерять доступ к нодам и административные права.",
      "Удалить",
    );
  if (
    (method === "POST" &&
      ["/roles", "/user-groups", "/unix-groups"].includes(route) &&
      data.id) ||
    (method === "PUT" && route.startsWith("/groups/"))
  )
    return action(
      "Изменить роль или группу?",
      "Изменения затронут всех участников и наследуемые назначения. Требования факторов, UNIX-права и доступ к нодам будут пересчитаны.",
    );
  if (
    /^\/(user-groups|unix-groups)\/(move|[^/]+\/(members(\/remove)?|bindings(\/[^/]+)?))$/.test(
      route,
    )
  )
    return action(
      "Изменить участников или права группы?",
      "Пользователи получат или потеряют групповые права и требования входа. При нехватке обязательных факторов доступ останется только к их регистрации.",
    );
  if (
    (method === "DELETE" && /^\/(tokens|join-tokens)\//.test(route)) ||
    (method === "PUT" && route.startsWith("/join-tokens/"))
  )
    return action(
      "Изменить или отозвать токен?",
      "Отозванный API-токен перестанет работать. Изменение join-токена влияет на новые подключения; уже присоединённые агенты используют свои сертификаты.",
    );
  if (method === "POST" && ["/tokens", "/join-tokens"].includes(route))
    return action(
      "Выпустить токен доступа?",
      route === "/tokens"
        ? "Токен предоставит доступ к API/MCP в пределах выбранных прав, групп и срока жизни. Храните секрет как пароль."
        : "Токен позволит присоединять ноды в выбранную группу до истечения срока или лимита использований. Получивший секрет сможет регистрировать новые ноды.",
      "Выпустить токен",
    );
  if (method === "POST" && /^\/nodes\/[^/]+\/recovery-token$/.test(route))
    return action(
      "Выпустить токен восстановления ноды?",
      "Токен позволяет заменить сертификат существующей ноды. После восстановления прежнее подключение агента перестанет действовать.",
      "Выпустить токен восстановления",
    );
  return null;
}
